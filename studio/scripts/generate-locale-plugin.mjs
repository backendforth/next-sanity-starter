#!/usr/bin/env node
/**
 * Optional: reads `siteLanguageSettings` and writes `config/generated/localePluginConfig.ts`
 * (for inspection or legacy tooling). The Studio plugin loads languages at runtime via
 * `config/sync/internationalizedArrayLanguages.ts` — you do **not** need this script for new locales.
 *
 * Run: `pnpm --filter studio exec node scripts/generate-locale-plugin.mjs`
 *
 * Uses the same dataset resolution as `studio/config/sync/studioDataset.ts` (see `studioCodegenResolveEnv.mjs`).
 * With `SANITY_API_READ_TOKEN` or `SANITY_STUDIO_DATASET_RESOLVER_TOKEN` in `studio/.env`, uses the
 * non-CDN API + `perspective=drafts` so **unpublished** language settings still codegen.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { loadEnvFile, studioRootFromScript } from "./loadEnvFile.mjs";
import { buildStudioResolveEnv } from "./studioCodegenResolveEnv.mjs";

const FALLBACK_LANGUAGES = [
  { id: "en", title: "English" },
  { id: "de", title: "Deutsch" },
];
const FALLBACK_DEFAULT = "en";

const studioRoot = studioRootFromScript(import.meta.url);
loadEnvFile(join(studioRoot, ".env"));

const outPath = join(studioRoot, "config/generated/localePluginConfig.ts");

function escapeString(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n");
}

function writeGenerated(languages, defaultId) {
  mkdirSync(join(studioRoot, "config/generated"), { recursive: true });
  const langLines = languages
    .map(
      (row) =>
        `  { id: "${escapeString(row.id)}", title: "${escapeString(row.title)}" },`,
    )
    .join("\n");
  const body = `/**
 * AUTO-GENERATED by \`node scripts/generate-locale-plugin.mjs\` — do not edit by hand.
 * Source: Sanity document \`siteLanguageSettings\` (Settings → Site languages).
 */
export const studioLanguages = [
${langLines}
] as const;

export const defaultLanguageIds = ["${escapeString(defaultId)}"] as const;
`;
  writeFileSync(outPath, body, "utf8");
  console.log(
    `[locale-codegen] Wrote ${outPath} (${languages.length} languages, default=${defaultId})`,
  );
}

function writeFallback(reason) {
  if (reason) {
    console.warn(`[locale-codegen] ${reason} — using fallback en + de`);
  }
  writeGenerated(FALLBACK_LANGUAGES, FALLBACK_DEFAULT);
}

async function fetchLanguageSettingsDoc(projectId, dataset) {
  const query = `*[_id == "siteLanguageSettings"][0]{availableLanguages[]{id,title},defaultLanguageId}`;
  const encoded = encodeURIComponent(query);
  const token =
    process.env.SANITY_API_READ_TOKEN?.trim() ||
    process.env.SANITY_STUDIO_DATASET_RESOLVER_TOKEN?.trim();

  if (token) {
    const url = new URL(
      `https://${projectId}.api.sanity.io/v2024-01-01/data/query/${dataset}`,
    );
    url.searchParams.set("query", query);
    url.searchParams.set("perspective", "drafts");
    const res = await fetch(url.toString(), {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!res.ok) {
      return { ok: false, status: res.status, json: null };
    }
    return { ok: true, status: res.status, json: await res.json() };
  }

  const url = `https://${projectId}.apicdn.sanity.io/v2024-01-01/data/query/${dataset}?query=${encoded}`;
  const res = await fetch(url);
  if (!res.ok) {
    return { ok: false, status: res.status, json: null };
  }
  return { ok: true, status: res.status, json: await res.json() };
}

async function main() {
  const projectId = process.env.SANITY_STUDIO_PROJECT_ID?.trim();
  if (!projectId) {
    writeFallback("Missing SANITY_STUDIO_PROJECT_ID");
    return;
  }

  let dataset;
  try {
    const mod = await import("@repo/sanity-dataset-resolve");
    dataset = await mod.resolveStudioDatasetAsync(buildStudioResolveEnv());
  } catch (e) {
    writeFallback(`Dataset resolve failed: ${e}`);
    return;
  }

  let json;
  try {
    const result = await fetchLanguageSettingsDoc(projectId, dataset);
    if (!result.ok) {
      writeFallback(`Query HTTP ${result.status}`);
      return;
    }
    json = result.json;
  } catch (e) {
    writeFallback(`Fetch failed: ${e}`);
    return;
  }

  const doc = json?.result;
  const rows = Array.isArray(doc?.availableLanguages)
    ? doc.availableLanguages
    : [];
  const normalized = rows
    .map((row) => ({
      id: typeof row?.id === "string" ? row.id.trim() : "",
      title: typeof row?.title === "string" ? row.title.trim() : "",
    }))
    .filter((row) => row.id.length > 0 && row.title.length > 0);

  const defaultId =
    typeof doc?.defaultLanguageId === "string"
      ? doc.defaultLanguageId.trim()
      : "";

  if (
    normalized.length === 0 ||
    !defaultId ||
    !normalized.some((r) => r.id === defaultId)
  ) {
    writeFallback("Singleton missing, empty, or default not in list");
    return;
  }

  writeGenerated(normalized, defaultId);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
